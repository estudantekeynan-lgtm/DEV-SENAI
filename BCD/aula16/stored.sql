CREATE PROCEDURE CONSULTAR_PRECO (IN P_ID_PRODUTO INT)
BEGIN
    DECLARE V_PRECO DECIMAL(10,2);

    SELECT PRECO
    INTO V_PRECO
    FROM PRODUTO
        WHERE ID_PRODUTO = P_ID_PRODUTO;


    SELECT V_PRECO AS PRECO_PRODUTO;
END $$

DELIMITER ;

CALL CONSULTAR_PRECO(2)

DELIMITER $$

CREATE PROCEDURE CLASSIFICAR_ESTOQUE (IN P_ID_PRODUTO INT)
BEGIN
    DECLARE V_QUANTIDADE INT;

    SELECT QUANTIDADE
    INTO V_QUANTIDADE
    FROM ESTOQUE
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    IF V_QUANTIDADE = 0 THEN
        SELECT 'SEM ESTOQUE' AS SITUACAO;
    ELSEIF V_QUANTIDADE <= 5 THEN
        SELECT 'ESTOQUE BAIXO' AS SITUACAO;
    ELSE
        SELECT 'ESTOQUE NORMAL' AS SITUACAO;
    END IF;
END $$

DELIMITER ;
CALL CLASSIFICAR_ESTOQUE(2)


